#!/usr/bin/env bash
# Refresh events-data.js, the bundled fallback used when /api/schedule is unavailable.
set -euo pipefail
cd "$(dirname "$0")/.."
URL='https://us.money2020.com/api/schedule?siteName=money2020-us&search=&agendaType=default'
json=$(curl -fsSL "$URL")
printf '// Generated by scripts/update-snapshot.sh on %s. Do not edit by hand.\nwindow.M2020_SCHEDULE_SNAPSHOT = %s;\n' "$(date -u +%Y-%m-%dT%H:%MZ)" "$json" > events-data.js
echo "Wrote events-data.js ($(printf '%s' "$json" | grep -o '"eventId"' | wc -l | tr -d ' ') events)"
